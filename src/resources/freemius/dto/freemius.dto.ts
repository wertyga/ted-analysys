import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import {
  IsArray,
  IsBoolean,
  IsNumber,
  IsOptional,
  IsString,
} from 'class-validator';

export class CreateFreemiusCheckoutDto {
  @ApiPropertyOptional({
    description:
      'Freemius plan ID to preselect in checkout. Omit it to use the default paid plan.',
    example: '12345',
  })
  @IsOptional()
  @IsString()
  planId?: string;

  @ApiPropertyOptional({
    description:
      'Existing Freemius license ID. Used only for upgrade/downgrade/change checkout flows.',
    example: '67890',
  })
  @IsOptional()
  @IsString()
  licenseId?: string;

  @ApiPropertyOptional({
    description:
      'Optional checkout quota/units for products using unit pricing.',
    example: 1,
  })
  @IsOptional()
  @IsNumber()
  quota?: number;

  @ApiPropertyOptional({
    description: 'Whether Freemius should include its recommended option.',
    default: true,
  })
  @IsOptional()
  @IsBoolean()
  withRecommendation?: boolean;
}

export class ChangeFreemiusSubscriptionDto {
  @ApiProperty({
    description: 'Target Freemius plan ID for the active subscription change.',
    example: '12345',
  })
  @IsString()
  planId: string;

  @ApiPropertyOptional({
    description: 'Optional target quota/units for the changed subscription.',
    example: 5,
  })
  @IsOptional()
  @IsNumber()
  quota?: number;

  @ApiPropertyOptional({
    description: 'Whether Freemius should include its recommended option.',
    default: true,
  })
  @IsOptional()
  @IsBoolean()
  withRecommendation?: boolean;
}

export class CancelFreemiusSubscriptionDto {
  @ApiPropertyOptional({
    description: 'Optional cancellation feedback passed to Freemius.',
    example: 'Too expensive',
  })
  @IsOptional()
  @IsString()
  feedback?: string;

  @ApiPropertyOptional({
    type: [Number],
    description:
      'Optional Freemius cancellation reason IDs. Freemius supports numeric reason IDs.',
    example: [1, 4],
  })
  @IsOptional()
  @IsArray()
  @IsNumber({}, { each: true })
  reasonIds?: number[];
}

export class FreemiusCheckoutResponseDto {
  @ApiProperty({
    description: 'Hosted checkout URL generated by Freemius.',
    example: 'https://checkout.freemius.com/mode/dialog/plugin/123/plan/456/',
  })
  link: string;

  @ApiProperty({
    description:
      'Options object for @freemius/checkout overlay. Shape is owned by Freemius SDK.',
    type: Object,
  })
  options: Record<string, unknown>;
}

export class FreemiusEntitlementResponseDto {
  @ApiPropertyOptional({
    description: 'Current active local Freemius entitlement, or null.',
    type: Object,
    nullable: true,
  })
  entitlement: Record<string, unknown> | null;
}

export class FreemiusWebhookResponseDto {
  @ApiProperty({ example: 200 })
  status: number;

  @ApiProperty({ example: true })
  success: boolean;

  @ApiPropertyOptional({ example: 'Invalid signature' })
  error?: string;
}

export class FreemiusCheckoutPurchaseDto {
  @ApiPropertyOptional({
    description: 'Freemius checkout purchase payload for paid purchases.',
    example: { license_id: '67890' },
  })
  purchase?: { license_id?: string };

  @ApiPropertyOptional({
    description: 'Freemius checkout trial payload for trial starts.',
    example: { license_id: '67890' },
  })
  trial?: { license_id?: string };
}
