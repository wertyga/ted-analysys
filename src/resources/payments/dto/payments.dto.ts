import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { Transform } from 'class-transformer';
import {
  IsArray,
  IsBoolean,
  IsInt,
  IsNotEmpty,
  IsNumber,
  IsOptional,
  IsString,
  Max,
  Min,
} from 'class-validator';

export class CreatePaymentCheckoutDto {
  @ApiPropertyOptional({
    description:
      'Freemius plan ID to preselect in checkout. Omit it to use the default paid plan.',
    example: '12345',
  })
  @IsString()
  @IsNotEmpty()
  planId: string;
}

export class ChangePaymentSubscriptionDto {
  @ApiProperty({
    description: 'Target Freemius plan ID for the active subscription change.',
    example: '12345',
  })
  @IsString()
  planId: string;

  @ApiPropertyOptional({
    description: 'Optional target quota/units for the changed subscription.',
    example: 5,
  })
  @IsOptional()
  @IsNumber()
  quota?: number;

  @ApiPropertyOptional({
    description: 'Whether Freemius should include its recommended option.',
    default: true,
  })
  @IsOptional()
  @IsBoolean()
  withRecommendation?: boolean;
}

export class CancelPaymentSubscriptionDto {
  @ApiPropertyOptional({
    description: 'Optional cancellation feedback passed to Freemius.',
    example: 'Too expensive',
  })
  @IsOptional()
  @IsString()
  feedback?: string;

  @ApiPropertyOptional({
    type: [Number],
    description:
      'Optional Freemius cancellation reason IDs. Freemius supports numeric reason IDs.',
    example: [1, 4],
  })
  @IsOptional()
  @IsArray()
  @IsNumber({}, { each: true })
  reasonIds?: number[];
}

export class PaymentCheckoutResponseDto {
  @ApiProperty({
    description: 'Hosted checkout URL generated by Freemius.',
    example: 'https://checkout.freemius.com/mode/dialog/plugin/123/plan/456/',
  })
  link: string;

  @ApiProperty({
    description:
      'Options object for @freemius/checkout overlay. Shape is owned by Freemius SDK.',
    type: Object,
  })
  options: Record<string, unknown>;
}

export class PaymentEntitlementResponseDto {
  @ApiPropertyOptional({
    description: 'Current active local Freemius entitlement, or null.',
    type: Object,
    nullable: true,
  })
  entitlement: Record<string, unknown> | null;
}

export class GetPaymentListDto {
  @ApiPropertyOptional({
    description: 'Number of Freemius payments to return.',
    example: 20,
    default: 20,
    maximum: 50,
  })
  @IsOptional()
  @IsInt()
  @Min(1)
  @Max(50)
  @Transform(({ value }) => Number(value))
  count: number = 20;

  @ApiPropertyOptional({
    description: 'Freemius payments offset.',
    example: 0,
    default: 0,
  })
  @IsOptional()
  @IsInt()
  @Min(0)
  @Transform(({ value }) => Number(value))
  offset: number = 0;
}

export class PaymentListResponseDto {
  @ApiProperty({
    description: 'Freemius payments for the authenticated user.',
    type: [Object],
  })
  payments: Record<string, unknown>[];
}

export class PaymentWebhookResponseDto {
  @ApiProperty({ example: 200 })
  status: number;

  @ApiProperty({ example: true })
  success: boolean;

  @ApiPropertyOptional({ example: 'Invalid signature' })
  error?: string;
}

export class PaymentCheckoutPurchaseDto {
  @ApiPropertyOptional({
    description: 'Freemius checkout purchase payload for paid purchases.',
    example: { license_id: '67890' },
  })
  purchase?: { license_id?: string };

  @ApiPropertyOptional({
    description: 'Freemius checkout trial payload for trial starts.',
    example: { license_id: '67890' },
  })
  trial?: { license_id?: string };
}
