export interface BuyerLegalTypeOption {
  code: BuyerLegalType;
  name: string;
  nodes?: BuyerLegalTypeOption[];
}

type BuyerLegalTypeJsonNode = {
  codes: string[];
  label: string;
  nodes?: BuyerLegalTypeJsonNode[];
};

function mapBuyerLegalTypeOptions(
  nodes: BuyerLegalTypeJsonNode[],
): BuyerLegalTypeOption[] {
  return nodes.flatMap((node) =>
    node.codes.map((code) => ({
      code: code as BuyerLegalType,
      name: node.label,
      nodes:
        node.nodes === undefined
          ? undefined
          : mapBuyerLegalTypeOptions(node.nodes),
    })),
  );
}

export const BUYER_LEGAL_TYPE_OPTIONS: BuyerLegalTypeOption[] =
  mapBuyerLegalTypeOptions(buyerLegalTypes.results);
