function safeStringify(
  value: unknown,
  maxChars = TENDER_DEEP_ANALYSIS_CONFIG.companyFitAnalysis.maxJsonChars,
): string {
  const json = JSON.stringify(value ?? null, null, 2);

  return json.length > maxChars
    ? `${json.slice(0, maxChars)}\n[TRUNCATED]`
    : json;
}
